/**
 * Builds the stress target's two large files.
 *
 * They are generated rather than kept in the repository because they are over
 * a megabyte between them and nothing about their contents is worth reading —
 * only their size is. Run `npm run fixtures` before using /stress/.
 *
 * Deterministic, so two people measuring the console are measuring the same
 * thing.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

/** Rows enough that converting the whole tree eagerly would be felt. */
const JSON_ROWS = 4000;
/** Lines enough to make the source viewer draw a few thousand rows. */
const JS_LINES = 6000;

const rows = Array.from({ length: JSON_ROWS }, (_, i) => ({
  id: i,
  name: `row-${i}`,
  tags: ['a', 'b', 'c'],
  nested: { deep: { er: { est: i } } },
  // Not ASCII on purpose: byte counts and character counts differ here.
  // Deliberately non-ASCII: a byte count and a character count must differ
  // here, or the size columns look right while being wrong.
  note: 'çàfé — ☕ '.repeat(3),
}));

const js = [
  '// Generated by make-fixtures.mjs — a deliberately large file, to see the',
  '// Sources viewer render one.',
  ...Array.from({ length: JS_LINES }, (_, i) => `export function helper${i}(a, b) { return a * ${i} + b; /* line ${i} */ }`),
].join('\n');

await fs.writeFile(path.join(here, 'big.json'), JSON.stringify({ rows }));
await fs.writeFile(path.join(here, 'big.js'), `${js}\n`);

for (const name of ['big.json', 'big.js']) {
  const { size } = await fs.stat(path.join(here, name));
  console.log(`[stress] ${name}  ${(size / 1024).toFixed(0)} kB`);
}
