/**
 * An agent key, shown without being handed out.
 *
 * The key decides which project a run records into, so a payload carrying it
 * is a payload that works. It used to be printed in full on every card of the
 * Projects screen — eight credentials at once, on the screen most likely to
 * end up in a screen share, a bug report or a screenshot pasted into a chat.
 *
 * The ends are kept because the one thing this screen is actually asked is
 * "which project is this key?", and four characters either side answers that
 * from a key found in a page or a log. Copy still takes the whole thing: a
 * value you cannot read is still a value you can paste.
 */
const ENDS = 4;

export function maskKey(key: string): string {
  if (!key) return '';
  /*
   * Too short for the ends to be a hint rather than most of the key. Nothing
   * generated by this relay is, but a file written by an older one could be,
   * and the safe answer for a key we cannot measure is to show none of it.
   */
  if (key.length < ENDS * 2 + 8) return '·'.repeat(Math.min(key.length, 12));
  return `${key.slice(0, ENDS)}…${key.slice(-ENDS)}`;
}
